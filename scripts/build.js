#!/usr/bin/env node
/**
 * Build lib/client.js from src/client/*.js.
 *
 * DSH loads a plugin's browser half as ONE plain script in its client-bundle format:
 *   window.__ModuleLoader__.load({ id, factory: (require) => { ...; return module.exports } })
 * where `require` reaches only the shell's shared modules ('react', '@deepseek-ai/dsh-client-ui-primitives').
 * The src/ modules are ordinary ES modules so node --test can import the DOM-free ones directly; this
 * script inlines them into that one factory: modules are ordered by their relative imports, import lines
 * are dropped, `export` keywords are stripped, and the shared modules are bound once in a prelude as the
 * globals `React` and `P`. No dependencies, no transforms beyond that.
 *
 *   node scripts/build.js          write lib/client.js
 *   node scripts/build.js --check  exit 1 when lib/client.js is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
const entry = resolve(root, 'src/client/index.js')
const out = resolve(root, 'lib/client.js')

const IMPORT = /^import\s+(?:[^'"]*?\s+from\s+)?['"]([^'"]+)['"]\s*;?\s*$/gm

/** Modules in dependency order (imports first), each read once. */
function collect(file, seen = new Map()) {
  if (seen.has(file)) return seen
  const source = readFileSync(file, 'utf8').replace(/\r\n/g, '\n') // a CRLF checkout builds the same bundle
  seen.set(file, null) // mark: in progress
  for (const match of source.matchAll(IMPORT)) {
    const spec = match[1]
    if (!spec.startsWith('.')) throw new Error(`${file}: only relative imports are bundled (got ${spec})`)
    collect(resolve(dirname(file), spec), seen)
  }
  seen.set(file, source)
  return seen
}

function strip(source) {
  return source
    .replace(IMPORT, '')
    .replace(/^export\s+\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|class\b)/gm, '')
    .replace(/^\/\* global [^*]*\*\/\s*$/gm, '')
    .trim()
}

const modules = [...collect(entry)].map(([file, source]) => ({ file, body: strip(source) }))

// One scope after inlining, so top-level names must be unique across modules.
const declared = new Map()
for (const { file, body } of modules) {
  for (const match of body.matchAll(/^(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    const name = match[1]
    if (declared.has(name)) throw new Error(`top-level "${name}" is declared in both ${declared.get(name)} and ${file}`)
    declared.set(name, file)
  }
}

const banner = `// ${pkg.name} ${pkg.version} — browser half. GENERATED by scripts/build.js from src/client/; edit the sources.
// DSH's own Workspace list keeps rendering every row, menu and hover card; this script only adds to it:
// folders, a fork tree, Claude-style drag effects, scrolling titles, menu actions and the settings page.
// Folder-plus icon paths from Lucide (ISC license, https://lucide.dev).`

const bundle = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    const React = require('react')
    const P = require('@deepseek-ai/dsh-client-ui-primitives')
${modules.map(({ file, body }) => `    // ---- ${file.slice(root.length + 1).replaceAll('\\', '/')}\n${body.replace(/^(?=.)/gm, '    ')}`).join('\n\n')}

    exports.inject = inject
    exports.apply = apply
    return module.exports
  }
})
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf8')
  } catch {}
  if (current.replace(/\r\n/g, '\n') !== bundle) {
    console.error('lib/client.js is stale: run `node scripts/build.js`')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  writeFileSync(out, bundle)
  console.log(`wrote lib/client.js (${modules.length} modules, ${bundle.length} bytes)`)
}
